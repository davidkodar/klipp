fn manifest(
    id: &str,
    name: &str,
    category: &str,
    description: &str,
    asset_kind: TemplateAssetKind,
    names: &[&str],
) -> TemplateManifest {
    let parameters = names
        .iter()
        .map(|name| (*name).to_string())
        .map(|name| {
            let value = if name.contains("speed") || name == "intensity" {
                TemplateValue::Number(0.5)
            } else if name == "accent" {
                TemplateValue::Color([0.63, 0.52, 1.0, 1.0])
            } else if name == "direction" || name == "status" || name == "icon" {
                TemplateValue::Enum("default".into())
            } else {
                TemplateValue::Text(String::new())
            };
            let label = name.replace('_', " ");
            (
                name,
                TemplateParameter {
                    label,
                    default: value,
                    range: None,
                    choices: Vec::new(),
                },
            )
        })
        .collect();
    TemplateManifest {
        id: id.into(),
        name: name.into(),
        category: category.into(),
        description: description.into(),
        asset_kind,
        version: 1,
        min_klipp_version: env!("CARGO_PKG_VERSION").into(),
        author: "Klipp".into(),
        license: "CC0-1.0".into(),
        parameters,
        media_slots: if asset_kind == TemplateAssetKind::MediaBacked {
            vec![TemplateMediaSlot {
                name: "screen".into(),
                label: "Screen media".into(),
                accepted: vec!["png".into(), "jpg".into(), "mp4".into(), "mov".into()],
                required: true,
            }]
        } else {
            Vec::new()
        },
    }
}

/// Shared with persisted timeline instances so templates can be edited by the
/// UI without making the timeline depend on this crate.
pub use klipp_core::TemplateValue;

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct NumberRange {
    pub min: Option<f64>,
    pub max: Option<f64>,
}

/// A parameter declaration and its default value.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct TemplateParameter {
    pub label: String,
    pub default: TemplateValue,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub range: Option<NumberRange>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub choices: Vec<String>,
}

impl TemplateParameter {
    pub fn validate(&self, value: &TemplateValue) -> Result<(), String> {
        let same_kind = matches!(
            (&self.default, value),
            (TemplateValue::Text(_), TemplateValue::Text(_))
                | (TemplateValue::Color(_), TemplateValue::Color(_))
                | (TemplateValue::Number(_), TemplateValue::Number(_))
                | (TemplateValue::Bool(_), TemplateValue::Bool(_))
                | (TemplateValue::Enum(_), TemplateValue::Enum(_))
        );
        if !same_kind {
            return Err(format!("value for '{}' has the wrong type", self.label));
        }
        if let TemplateValue::Number(number) = value {
            // NaN and infinity have no JSON form: serde writes `null`,
            // and the saved template would never load again.
            if !number.is_finite() {
                return Err(format!("value for '{}' is not a number", self.label));
            }
            if let Some(range) = &self.range {
                if range.min.is_some_and(|min| *number < min)
                    || range.max.is_some_and(|max| *number > max)
                {
                    return Err(format!("value for '{}' is outside its range", self.label));
                }
            }
        }
        if let TemplateValue::Enum(choice) = value {
            if !self.choices.is_empty() && !self.choices.iter().any(|item| item == choice) {
                return Err(format!("unknown choice '{choice}' for '{}'", self.label));
            }
        }
        Ok(())
    }
}

/// A binding from an exposed parameter to a property in the ordinary
/// composition.  The property path is intentionally opaque to this layer;
/// the document resolver owns its interpretation and can evolve it without
/// changing the on-disk template registry.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TemplateBinding {
    pub parameter: String,
    pub property: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CompositionTemplate {
    pub format_version: u32,
    pub id: Uuid,
    pub name: String,
    #[serde(default)]
    pub category: String,
    /// The sequence/precomposition that supplies the actual layers.
    pub composition_id: Uuid,
    #[serde(default)]
    pub parameters: BTreeMap<String, TemplateParameter>,
    #[serde(default)]
    pub bindings: Vec<TemplateBinding>,
    #[serde(default)]
    pub written_by: String,
}

impl CompositionTemplate {
    pub fn validate(&self) -> Result<(), String> {
        if self.format_version == 0 || self.format_version > FORMAT_VERSION {
            return Err(format!(
                "unsupported template format {}",
                self.format_version
            ));
        }
        if self.name.trim().is_empty() {
            return Err("a template needs a name".into());
        }
        for (name, parameter) in &self.parameters {
            parameter
                .validate(&parameter.default)
                .map_err(|error| format!("parameter '{name}': {error}"))?;
        }
        for binding in &self.bindings {
            if !self.parameters.contains_key(&binding.parameter) {
                return Err(format!(
                    "binding references unknown parameter '{}'",
                    binding.parameter
                ));
            }
            if binding.property.trim().is_empty() {
                return Err(format!(
                    "binding for '{}' has no property",
                    binding.parameter
                ));
            }
        }
        Ok(())
    }

    pub fn new(name: impl Into<String>, composition_id: Uuid) -> Self {
        Self {
            format_version: FORMAT_VERSION,
            id: Uuid::new_v4(),
            name: name.into(),
            category: String::new(),
            composition_id,
            parameters: BTreeMap::new(),
            bindings: Vec::new(),
            written_by: env!("CARGO_PKG_VERSION").to_string(),
        }
    }
}

/// Build a starter template from a composition. The first text object becomes
/// an exposed `text` parameter; more elaborate parameter authoring remains a
/// later slice, while the saved composition is already reusable and editable.
pub fn template_from_sequence(sequence: &klipp_timeline::Sequence, name: impl Into<String>) -> CompositionTemplate {
    let mut template = CompositionTemplate::new(name, sequence.id.0);
    if let Some(title) = sequence.tracks.iter().flat_map(|track| &track.clips).find_map(|clip| match &clip.kind {
        klipp_timeline::ClipKind::Title(title) => Some(title),
        _ => None,
    }) {
        if let Some((index, text)) = title.objects.iter().enumerate().find_map(|(index, object)| match &object.content {
            klipp_timeline::TitleObjectContent::TextBox(text) => Some((index, text.text.clone())),
            _ => None,
        }) {
            template.parameters.insert("text".into(), TemplateParameter {
                label: "Text".into(),
                default: TemplateValue::Text(text),
                range: None,
                choices: Vec::new(),
            });
            template.bindings.push(TemplateBinding { parameter: "text".into(), property: format!("object:{index}.text") });
        }
    }
    template
}

/// Save a composition as a template in the store. The composition's
/// existing template, found by `composition_id`, is replaced — same id,
/// same file — so saving twice does not make two; a composition with no
/// template yet gets a new one. Returns whether one was replaced.
pub fn save_composition_as_template(
    store: &mut CompositionTemplateStore,
    sequence: &klipp_timeline::Sequence,
    name: impl Into<String>,
) -> Result<bool, String> {
    let mut template = template_from_sequence(sequence, name);
    let existing = store.templates().find(|existing| existing.composition_id == sequence.id.0).map(|existing| existing.id);
    if let Some(id) = existing {
        template.id = id;
    }
    store.save(template)?;
    Ok(existing.is_some())
}

/// The bundled terminal card used by the Lunel-style launch-film workflow.
///
/// This is deliberately ordinary title content: a dark rounded panel, a
/// monospaced command line and a blinking cursor. The card enters and exits
/// with eased motion, drifts a few pixels while held, and carries the same
/// motion-blur path as any hand-built title. The stable object ids are used by
/// the template bindings below.
pub fn terminal_card_composition() -> TitleData {
    let mut title = TitleData::default();
    title.objects.clear();
    title.next_object_id = 0;
    let card_transform = ObjectTransform {
        center: TitlePosition { x: 0.5, y: 0.5 },
        center_x_keyframes: eased(&[
            (0.0, 0.44, Easing::OutCubic),
            (0.16, 0.5, Easing::OutCubic),
            (0.55, 0.5, Easing::InOutCubic),
            (0.9, 0.505, Easing::InOutCubic),
            (1.25, 0.49, Easing::OutCubic),
        ]),
        center_y_keyframes: eased(&[
            (0.0, 0.52, Easing::OutCubic),
            (0.16, 0.5, Easing::OutCubic),
            (0.72, 0.497, Easing::InOutCubic),
            (1.1, 0.503, Easing::InOutCubic),
            (1.3, 0.5, Easing::OutCubic),
        ]),
        size: TitlePosition { x: 0.42, y: 0.22 },
        rotation: 0.0,
        anchor_norm: TitlePosition { x: 0.5, y: 0.5 },
        size_x_keyframes: Vec::new(), size_y_keyframes: Vec::new(), rotation_keyframes: Vec::new(), anchor_x_keyframes: Vec::new(), anchor_y_keyframes: Vec::new(),
    };
    let mut card_fx = LayerFx {
        motion: TitleMotion::both(
            Motion::new(MotionKind::SlideRight)
                .duration(0.16)
                .easing(Easing::OutCubic)
                .distance(0.7),
            Motion::new(MotionKind::SlideLeft)
                .duration(0.18)
                .delay(0.05)
                .easing(Easing::InCubic)
                .distance(0.7),
        ),
        motion_blur: Some(MotionBlur {
            enabled: true,
            shutter_angle: 180.0,
            shutter_angle_keyframes: Vec::new(),
            samples: 8,
        }),
        glows: vec![TextGlow {
            enabled: true,
            color: [132, 96, 255, 170],
            radius: 20.0,
            radius_keyframes: Vec::new(),
            intensity: 0.35,
            intensity_keyframes: Vec::new(),
        }],
        ..LayerFx::default()
    };
    card_fx.loops.push(TitleLoop::Pulse {
        rate_hz: 0.55,
        min_opacity: 0.94,
    });
    let card_id = title.add_object(
        TitleObjectContent::Shape(Shape {
            kind: ShapeKind::Rectangle {
                corner_radius: 24.0,
            },
            fill: Some([18, 17, 29, 244]),
            gradient: None,
            stroke: Some(ShapeStroke {
                color: [115, 92, 190, 180],
                width: 2.0,
            }),
            fit: None,
        }),
        card_transform,
    );
    if let Some(card) = title.object_mut(card_id) {
        card.fx = Some(card_fx);
    }

    let command = TextBox {
        text: "$ find invoice.pdf".into(),
        font_size: 42.0,
        font_name: "JetBrains Mono".into(),
        color: [235, 231, 255, 255],
        alignment: TextAlignment::Left,
        ..TextBox::default()
    };
    let command_len = command.text.chars().count().max(1) as f32;
    let text_transform = ObjectTransform {
        center: TitlePosition { x: 0.5, y: 0.49 },
        center_x_keyframes: Vec::new(),
        center_y_keyframes: Vec::new(),
        size: TitlePosition { x: 0.34, y: 0.08 },
        rotation: 0.0,
        anchor_norm: TitlePosition { x: 0.5, y: 0.5 },
        size_x_keyframes: Vec::new(), size_y_keyframes: Vec::new(), rotation_keyframes: Vec::new(), anchor_x_keyframes: Vec::new(), anchor_y_keyframes: Vec::new(),
    };
    let text_fx = LayerFx {
        motion: TitleMotion::both(
            // Typewriter is a step per unit: without a stagger the whole
            // line pops in at once. One character every 0.02 s makes the
            // 0.34 s the parameter names.
            Motion::new(MotionKind::Typewriter)
                .duration(0.02)
                .stagger(StaggerUnit::Char, 0.34 / command_len)
                .easing(Easing::Linear),
            Motion::new(MotionKind::Fade)
                .duration(0.12)
                .easing(Easing::InCubic),
        ),
        motion_blur: Some(MotionBlur {
            enabled: true,
            shutter_angle: 140.0,
            shutter_angle_keyframes: Vec::new(),
            samples: 6,
        }),
        glows: vec![TextGlow {
            enabled: true,
            color: [160, 132, 255, 150],
            radius: 9.0,
            radius_keyframes: Vec::new(),
            intensity: 0.4,
            intensity_keyframes: Vec::new(),
        }],
        ..LayerFx::default()
    };
    let command_id = title.add_object(TitleObjectContent::TextBox(command), text_transform);
    if let Some(command_object) = title.object_mut(command_id) {
        command_object.fx = Some(text_fx);
    }

    let cursor_transform = ObjectTransform {
        center: TitlePosition { x: 0.63, y: 0.49 },
        center_x_keyframes: Vec::new(),
        center_y_keyframes: Vec::new(),
        size: TitlePosition { x: 0.008, y: 0.065 },
        rotation: 0.0,
        anchor_norm: TitlePosition { x: 0.5, y: 0.5 },
        size_x_keyframes: Vec::new(), size_y_keyframes: Vec::new(), rotation_keyframes: Vec::new(), anchor_x_keyframes: Vec::new(), anchor_y_keyframes: Vec::new(),
    };
    let cursor_fx = LayerFx {
        loops: vec![TitleLoop::Blink {
            rate_hz: 2.2,
            duty: 0.5,
        }],
        ..LayerFx::default()
    };
    let cursor_id = title.add_object(
        TitleObjectContent::Shape(Shape {
            kind: ShapeKind::Rectangle { corner_radius: 2.0 },
            fill: Some([184, 157, 255, 255]),
            gradient: None,
            stroke: None,
            fit: None,
        }),
        cursor_transform,
    );
    if let Some(cursor) = title.object_mut(cursor_id) {
        cursor.fx = Some(cursor_fx);
    }
    title
}

