/// The keys of one moving value, each segment eased into its key by the
/// named curve: the same handles the `camera` op and the curve editor
/// write, so what the card does is what a person would key by hand.
fn eased(keys: &[(f64, f32, Easing)]) -> Vec<klipp_core::Keyframe> {
    let mut out: Vec<klipp_core::Keyframe> = keys
        .iter()
        .map(|(time_secs, value, _)| klipp_core::Keyframe {
            time_secs: *time_secs,
            value: *value,
            interpolation: klipp_core::Interpolation::Linear,
            tangent_out: (0.0, 0.0),
            tangent_in: (0.0, 0.0),
            handles: Default::default(),
        })
        .collect();
    for (i, (_, _, easing)) in keys.iter().enumerate() {
        let ease = match easing {
            Easing::InCubic => klipp_core::keyframe::Ease::In,
            Easing::OutCubic => klipp_core::keyframe::Ease::Out,
            Easing::InOutCubic => klipp_core::keyframe::Ease::InOut,
            _ => klipp_core::keyframe::Ease::Linear,
        };
        klipp_core::keyframe::ease_into(&mut out, i, ease);
    }
    out
}

/// An inserted template instance. The data lives in core so it can be stored
/// on a timeline clip; these helpers keep catalogue validation in the UI.
pub use klipp_core::TemplateInstance;

trait TemplateInstanceExt {
    #[allow(dead_code)]
    fn set(
        &mut self,
        template: &CompositionTemplate,
        name: &str,
        value: TemplateValue,
    ) -> Result<(), String>;
    #[allow(dead_code)]
    fn value<'a>(
        &'a self,
        template: &'a CompositionTemplate,
        name: &str,
    ) -> Option<&'a TemplateValue>;
}

impl TemplateInstanceExt for TemplateInstance {
    fn set(
        &mut self,
        template: &CompositionTemplate,
        name: &str,
        value: TemplateValue,
    ) -> Result<(), String> {
        let parameter = template
            .parameters
            .get(name)
            .ok_or_else(|| format!("template has no parameter '{name}'"))?;
        parameter.validate(&value)?;
        self.overrides.insert(name.to_string(), value);
        Ok(())
    }

    fn value<'a>(
        &'a self,
        template: &'a CompositionTemplate,
        name: &str,
    ) -> Option<&'a TemplateValue> {
        self.overrides.get(name).or_else(|| {
            template
                .parameters
                .get(name)
                .map(|parameter| &parameter.default)
        })
    }
}

#[derive(Debug, Default)]
pub struct CompositionTemplateStore {
    dir: Option<PathBuf>,
    entries: Vec<(PathBuf, CompositionTemplate)>,
}

impl CompositionTemplateStore {
    pub fn load_default() -> Self {
        Self::load(dirs::config_dir().map(|dir| dir.join("klipp").join("templates")))
    }

    pub fn load(dir: Option<PathBuf>) -> Self {
        let mut entries = Vec::new();
        if let Some(Ok(read)) = dir.as_deref().map(std::fs::read_dir) {
            for path in read.flatten().map(|entry| entry.path()) {
                if path.extension().and_then(|extension| extension.to_str()) != Some(EXTENSION) {
                    continue;
                }
                match std::fs::read_to_string(&path)
                    .map_err(|error| error.to_string())
                    .and_then(|json| {
                        serde_json::from_str::<CompositionTemplate>(&json)
                            .map_err(|error| error.to_string())
                    }) {
                    Ok(template) if template.validate().is_ok() => {
                        // One id is one template: a second file carrying
                        // it is a copy, and saving would rewrite the
                        // first while dropping both from the list.
                        if entries
                            .iter()
                            .any(|(_, existing): &(PathBuf, CompositionTemplate)| {
                                existing.id == template.id
                            })
                        {
                            tracing::warn!("Skipping template '{}': its id is already loaded from another file", path.display());
                        } else {
                            entries.push((path, template));
                        }
                    }
                    Ok(template) => tracing::warn!(
                        "Skipping invalid template '{}': {}",
                        path.display(),
                        template.validate().unwrap_err()
                    ),
                    Err(error) => tracing::warn!("Skipping template '{}': {error}", path.display()),
                }
            }
        }
        entries.sort_by_key(|(path, template)| (template.name.to_lowercase(), path.clone()));
        Self { dir, entries }
    }

    pub fn templates(&self) -> impl Iterator<Item = &CompositionTemplate> {
        self.entries.iter().map(|(_, template)| template)
    }

    pub fn save(&mut self, template: CompositionTemplate) -> Result<(), String> {
        template.validate()?;
        let dir = self
            .dir
            .as_ref()
            .ok_or("no template directory configured")?;
        std::fs::create_dir_all(dir).map_err(|error| error.to_string())?;
        let path = self
            .entries
            .iter()
            .find(|(_, existing)| existing.id == template.id)
            .map(|(path, _)| path.clone())
            .unwrap_or_else(|| {
                // A new template named like another gets a file of its
                // own rather than the other's.
                let stem = safe_stem(&template.name);
                let taken = |p: &PathBuf| self.entries.iter().any(|(existing, _)| existing == p);
                let mut candidate = dir.join(format!("{stem}.{EXTENSION}"));
                let mut n = 2;
                while taken(&candidate) || candidate.exists() {
                    candidate = dir.join(format!("{stem}-{n}.{EXTENSION}"));
                    n += 1;
                }
                candidate
            });
        let json = serde_json::to_string_pretty(&template).map_err(|error| error.to_string())?;
        std::fs::write(&path, json).map_err(|error| error.to_string())?;
        self.entries
            .retain(|(_, existing)| existing.id != template.id);
        self.entries.push((path, template));
        self.entries
            .sort_by_key(|(path, item)| (item.name.to_lowercase(), path.clone()));
        Ok(())
    }
}

fn safe_stem(name: &str) -> String {
    let stem: String = name
        .chars()
        .map(|character| {
            if character.is_alphanumeric() || character == '-' || character == '_' {
                character
            } else {
                '_'
            }
        })
        .collect();
    if stem.is_empty() {
        "template".into()
    } else {
        stem
    }
}

