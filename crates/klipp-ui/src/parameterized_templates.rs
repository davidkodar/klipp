/// How a template gets its visible content.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum TemplateAssetKind {
    /// Content is generated by ordinary Klipp layers and exposed parameters.
    Procedural,
    /// Content comes from user-supplied image/video slots inside the template.
    MediaBacked,
}

/// A media placeholder declared by a template package. Media-backed
/// templates never execute code: they only ask the user to supply a file.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TemplateMediaSlot {
    pub name: String,
    pub label: String,
    pub accepted: Vec<String>,
    #[serde(default)]
    pub required: bool,
}

/// Catalog metadata shown before a template is inserted. This is separate
/// from [`CompositionTemplate`] because built-ins can be advertised before a
/// project has materialised their composition sequence.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct TemplateManifest {
    pub id: String,
    pub name: String,
    pub category: String,
    pub description: String,
    pub asset_kind: TemplateAssetKind,
    pub version: u32,
    pub min_klipp_version: String,
    pub author: String,
    pub license: String,
    #[serde(default)]
    pub parameters: BTreeMap<String, TemplateParameter>,
    #[serde(default)]
    pub media_slots: Vec<TemplateMediaSlot>,
}

