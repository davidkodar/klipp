pub struct TemplateManifest {
    pub id: String,
    pub name: String,
    pub category: String,
    pub description: String,
    pub asset_kind: TemplateAssetKind,
    pub version: u32,
    pub min_klipp_version: String,
    pub author: String,
    pub license: String,
    #[serde(default)]
    pub parameters: BTreeMap<String, TemplateParameter>,
    #[serde(default)]
    pub media_slots: Vec<TemplateMediaSlot>,
}

